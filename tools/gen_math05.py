Q = []

def mc(cat, q, right, wrongs, exp, fig=None):
    wrongs = [w for w in dict.fromkeys(map(str, wrongs)) if w != str(right)][:3]
    assert len(wrongs) == 3, (q, right, wrongs)
    opts = [str(right)] + wrongs
    random.shuffle(opts)
    d = {'type': 'mc', 'cat': cat, 'q': q, 'opts': opts, 'ans': opts.index(str(right)), 'exp': exp}
    if fig: d['fig'] = fig
    Q.append(d)

def tf(cat, q, ok, exp, fig=None):
    d = {'type': 'tf', 'cat': cat, 'q': q, 'opts': ['○ 正確', '✕ 錯誤'], 'ans': 0 if ok else 1, 'exp': exp}
    if fig: d['fig'] = fig
    Q.append(d)

def reg(n, cx=110, cy=78, r=58, rot=-90):
    return [[round(cx + r * math.cos(math.radians(rot + 360 * i / n)), 1), round(cy + r * math.sin(math.radians(rot + 360 * i / n)), 1)] for i in range(n)]

def F(*polys, lines=None, labels=None, circles=None):
    f = {'w': 220, 'h': 156, 'polys': [{'pts': p} for p in polys]}
    if lines: f['lines'] = lines
    if labels: f['labels'] = labels
    if circles: f['circles'] = circles
    return f

