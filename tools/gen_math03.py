def mc(cat, q, right, wrongs, exp, fig=None):
    wrongs = [w for w in dict.fromkeys(map(str, wrongs)) if w != str(right)][:3]
    assert len(wrongs) == 3, (q, right, wrongs)
    opts = [str(right)] + wrongs
    random.shuffle(opts)
    d = {'type': 'mc', 'cat': cat, 'q': q, 'opts': opts, 'ans': opts.index(str(right)), 'exp': exp}
    if fig: d['fig'] = fig
    Q.append(d)

def tf(cat, q, ok, exp, fig=None):
    d = {'type': 'tf', 'cat': cat, 'q': q, 'opts': ['○ 正確', '✕ 錯誤'], 'ans': 0 if ok else 1, 'exp': exp}
    if fig: d['fig'] = fig
    Q.append(d)

def pts(n, irregular=False, cx=110, cy=76, r=60, rot=-90):
    out = []
    for i in range(n):
        a = math.radians(rot + 360 * i / n + (random.uniform(-12, 12) if irregular else 0))
        rr = r * (random.uniform(0.72, 1.0) if irregular else 1)
        out.append([round(cx + rr * math.cos(a), 1), round(cy + rr * math.sin(a), 1)])
    return out

def poly_fig(p, diag_from=None, dots=False):
    f = {'w': 220, 'h': 152, 'polys': [{'pts': p, 'dots': dots}]}
    if diag_from is not None:
        n = len(p)
        f['lines'] = [[*p[diag_from], *p[j], 1] for j in range(n) if j not in (diag_from, (diag_from + 1) % n, (diag_from - 1) % n)]
    return f

