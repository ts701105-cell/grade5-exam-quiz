MARK0, MARK1 = '// ==== 課本題（tools/textbook_math.py 產生）====', '// ==== 課本題結束 ===='
for uid, items in NEW.items():
    p = D / f'{uid}.js'
    s = p.read_text(encoding='utf-8')
    for i, q in enumerate(items, 1):
        q['id'] = f'{uid}-t{i:03d}'
    if MARK0 in s:
        s = s[:s.index(MARK0)].rstrip() + '\n'
    if s.lstrip('/ \n').find('(function') != -1 and "window.QUIZ_BANK['%s'] = {\n    subject" % uid in s:
        # 手寫格式（math-01）：在檔案最後追加
        s = s.replace(re.search(r'— \d+ 題', s).group(0), '— %d 題' % (100 + len(items)), 1)
        s += MARK0 + '\n(function () {\n  const B = window.QUIZ_BANK[%r];\n  B.questions = B.questions.concat(%s);\n})();\n' % (uid, json.dumps(items, ensure_ascii=False, indent=1)) + MARK1 + '\n'
        p.write_text(s, encoding='utf-8'); print(uid, '課本題', len(items)); continue
    head, body = s.split(f"window.QUIZ_BANK['{uid}'] = ", 1)
    bank = json.loads(body.strip().rstrip(';'))
    qs = [q for q in bank['questions'] if q.get('cat') != K and '可以被 3 整除' not in q['q']]
    bank['questions'] = qs + items
    n = len(bank['questions'])
    head = re.sub(r'— \d+ 題', f'— {n} 題', head)
    p.write_text(head + f"window.QUIZ_BANK['{uid}'] = " + json.dumps(bank, ensure_ascii=False, indent=1) + ';\n', encoding='utf-8')
    print(uid, '共', n, '題，課本題', len(items))
