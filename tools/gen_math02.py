import json, random
from math import gcd

random.seed(20261001)
Q = []

def lcm(a, b): return a * b // gcd(a, b)
def factors(n): return [d for d in range(1, n + 1) if n % d == 0]
def fl(xs): return '、'.join(map(str, xs))

def mc(cat, q, right, wrongs, exp):
    wrongs = [w for w in dict.fromkeys(wrongs) if w != right][:3]
    assert len(wrongs) == 3, (q, right, wrongs)
    opts = [str(right)] + [str(w) for w in wrongs]
    random.shuffle(opts)
    Q.append({'type': 'mc', 'cat': cat, 'q': q, 'opts': opts, 'ans': opts.index(str(right)), 'exp': exp})

def tf(cat, q, ok, exp):
    Q.append({'type': 'tf', 'cat': cat, 'q': q, 'opts': ['○ 正確', '✕ 錯誤'], 'ans': 0 if ok else 1, 'exp': exp})

# ───── 2-1 整除（14）─────
for a, b in [(84, 7), (96, 8), (126, 9), (75, 6), (91, 13), (100, 12)]:
    ok = a % b == 0
    tf('整除', f'{a} ÷ {b} 可以整除。', ok,
       f'{a} ÷ {b} = {a // b}' + ('，沒有餘數，所以可以整除。' if ok else f' 餘 {a % b}，有餘數，所以不能整除。'))
cands = [(72, 8), (65, 4), (58, 6), (83, 9)]
mc('整除', '下列哪一個算式可以「整除」？', f'{cands[0][0]} ÷ {cands[0][1]}',
   [f'{a} ÷ {b}' for a, b in cands[1:]], '72 ÷ 8 = 9 沒有餘數；65 ÷ 4 餘 1、58 ÷ 6 餘 4、83 ÷ 9 餘 2。')
cands = [(54, 6), (63, 7), (48, 5), (88, 11)]
mc('整除', '下列哪一個算式「不能」整除？', '48 ÷ 5', ['54 ÷ 6', '63 ÷ 7', '88 ÷ 11'], '48 ÷ 5 = 9 餘 3，有餘數，不能整除。')
mc('整除', '「整除」的意思是什麼？', '除法算完沒有餘數', ['商是偶數', '被除數比除數大', '除數是 1'], '整數除以整數，商是整數而且餘數是 0，叫做整除。')
mc('整除', '下列哪一個數可以被 2 整除？', 358, [357, 125, 491], '個位數字是 0、2、4、6、8 的數都可以被 2 整除，358 的個位是 8。')
mc('整除', '下列哪一個數可以被 5 整除？', 735, [732, 548, 919], '個位數字是 0 或 5 的數可以被 5 整除，735 的個位是 5。')
mc('整除', '下列哪一個數可以同時被 2 和 5 整除？', 640, [645, 248, 515], '同時被 2 和 5 整除，個位數字一定是 0。')
mc('整除', '下列哪一個數可以被 3 整除？', 471, [472, 205, 341], '各位數字相加是 3 的倍數，就能被 3 整除：4 + 7 + 1 = 12。')
tf('整除', '個位數字是 5 的數，一定可以被 5 整除。', True, '個位是 0 或 5 的數都能被 5 整除。')

# ───── 2-2 因數（26）─────
for n in [12, 18, 20, 24, 30, 36]:
    f = factors(n)
    wrong1 = f[:-1]                                # 漏掉自己
    wrong2 = [x for x in f if x != 1]              # 漏掉 1
    extra = sorted(set(f + [max(d for d in range(2, n) if n % d)]))  # 多一個不是因數的數
    mc('因數', f'{n} 的因數有哪些？', fl(f), [fl(wrong1), fl(wrong2), fl(extra)],
       f'{n} 的因數是能整除 {n} 的數：{fl(f)}，別忘了 1 和 {n} 自己。')
for n in [16, 28, 32, 40, 45, 48]:
    k = len(factors(n))
    mc('因數', f'{n} 一共有幾個因數？', k, [k - 1, k + 1, k - 2 if k > 3 else k + 2],
       f'{n} 的因數是 {fl(factors(n))}，共 {k} 個。')
for n, x in [(42, 7), (56, 8), (60, 9), (27, 6), (39, 13), (64, 12)]:
    ok = n % x == 0
    tf('因數', f'{x} 是 {n} 的因數。', ok,
       f'{n} ÷ {x} = {n // x}，可以整除，所以 {x} 是 {n} 的因數。' if ok else f'{n} ÷ {x} 有餘數（餘 {n % x}），所以 {x} 不是 {n} 的因數。')
mc('因數', '下列哪一個數「不是」36 的因數？', 8, [4, 9, 12], '36 ÷ 8 = 4 餘 4，不能整除，所以 8 不是 36 的因數。')
mc('因數', '任何一個整數（0 除外）一定有哪一個因數？', 1, [2, 3, 10], '每個整數都能被 1 整除，所以 1 是每個整數的因數。')
mc('因數', '一個數最大的因數是什麼？', '它自己', ['它的一半', '1', '沒有最大的因數'], '一個數最大的因數就是它自己，例如 15 最大的因數是 15。')
mc('因數', '下列哪一個數只有 1 和它自己兩個因數？', 13, [15, 21, 9], '13 只能被 1 和 13 整除；15、21、9 都還有其他因數。')
mc('因數', '小明說「6 × 4 = 24」，下列哪一句話正確？', '6 和 4 都是 24 的因數', ['24 是 6 的因數', '6 是 4 的因數', '4 是 6 的倍數'], '6 × 4 = 24，所以 6 和 4 都是 24 的因數，24 是 6 和 4 的倍數。')
tf('因數', '1 是所有整數（0 除外）的因數。', True, '任何整數 ÷ 1 都能整除。')
tf('因數', '一個數的因數個數是無限多個。', False, '因數不會比這個數大，所以個數是有限的；倍數才有無限多個。')
tf('因數', '一個數最小的因數是 1，最大的因數是它自己。', True, '例如 20 的因數從 1 到 20。')

# ───── 倍數（14）─────
for n in [6, 7, 9, 12]:
    m = [n * i for i in range(1, 6)]
    mc('倍數', f'{n} 的前 5 個倍數是哪些？', fl(m), [fl([n * i for i in range(0, 5)]), fl([n + i for i in range(5)]),
       fl([n * i for i in range(2, 7)])], f'{n} 的倍數是 {n} × 1、{n} × 2……：{fl(m)}。')
mc('倍數', '在 1～50 之間，8 的倍數有幾個？', 6, [5, 7, 8], '8、16、24、32、40、48，共 6 個（50 ÷ 8 = 6 餘 2）。')
mc('倍數', '在 1～100 之間，15 的倍數有幾個？', 6, [5, 7, 15], '15、30、45、60、75、90，共 6 個（100 ÷ 15 = 6 餘 10）。')
mc('倍數', '下列哪一個數是 7 的倍數？', 91, [93, 74, 66], '91 ÷ 7 = 13，可以整除，所以 91 是 7 的倍數。')
mc('倍數', '下列哪一個數「不是」9 的倍數？', 84, [81, 99, 108], '84 ÷ 9 = 9 餘 3，不能整除。')
mc('倍數', '比 50 大、最接近 50 的 6 的倍數是多少？', 54, [48, 56, 60], '6 × 9 = 54 > 50，6 × 8 = 48 < 50，所以是 54。')
tf('倍數', '一個數的倍數有無限多個。', True, '可以一直乘下去：× 1、× 2、× 3……沒有最後一個。')
tf('倍數', '一個數最小的倍數是它自己（0 除外）。', True, '例如 8 最小的倍數是 8 × 1 = 8。')
tf('倍數', '如果 a 是 b 的因數，那麼 b 就是 a 的倍數。', True, '例如 3 是 12 的因數，12 就是 3 的倍數。')
tf('倍數', '35 是 5 的因數。', False, '35 = 5 × 7，35 是 5 的倍數，5 才是 35 的因數。')

# ───── 2-3 公因數與最大公因數（26）─────
for a, b in [(12, 18), (16, 24), (20, 30), (18, 27), (24, 36), (15, 25)]:
    cf = [d for d in factors(a) if b % d == 0]
    g = cf[-1]
    mc('公因數', f'{a} 和 {b} 的公因數有哪些？', fl(cf),
       [fl(cf[:-1]), fl(cf[1:]), fl(sorted(set(cf + [x for x in factors(a) if x not in cf][:1])))],
       f'{a} 的因數：{fl(factors(a))}；{b} 的因數：{fl(factors(b))}。兩個都有的是 {fl(cf)}。')
for a, b in [(28, 42), (36, 48), (45, 60), (32, 40), (54, 72), (26, 39)]:
    g = gcd(a, b)
    cf = [d for d in factors(g)]
    mc('最大公因數', f'{a} 和 {b} 的最大公因數是多少？', g,
       [cf[-2] if len(cf) > 1 else 1, g * 2, a - b if a > b else b - a if (b - a) != g else g + 1],
       f'{a} 和 {b} 的公因數是 {fl(cf)}，最大的是 {g}。')
mc('最大公因數', '兩個數的最大公因數是 1，下列哪一組符合？', '8 和 15', ['6 和 9', '10 和 25', '12 和 18'], '8 的因數 1、2、4、8；15 的因數 1、3、5、15，只有 1 是公因數。')
mc('公因數', '任何兩個整數，一定都有哪一個公因數？', 1, [2, 0, 5], '1 是所有整數的因數，所以一定是公因數。')
mc('最大公因數', '如果 a 是 b 的因數，那麼 a 和 b 的最大公因數是多少？', 'a', ['b', '1', 'a × b'], '例如 6 是 18 的因數，6 和 18 的最大公因數就是 6。')
mc('最大公因數', '18、24、30 三個數的最大公因數是多少？', 6, [3, 2, 12], '三個數的公因數是 1、2、3、6，最大是 6。')
tf('公因數', '兩個數的公因數，一定也是它們最大公因數的因數。', True, '例如 12 和 18 的公因數 1、2、3、6，都是最大公因數 6 的因數。')
tf('最大公因數', '20 和 30 的最大公因數是 5。', False, '20 和 30 的公因數有 1、2、5、10，最大是 10。')
tf('公因數', '9 和 16 沒有公因數。', False, '9 和 16 有公因數 1，只是最大公因數是 1。')
tf('最大公因數', '兩個數的最大公因數，不會比兩個數中較小的那個數大。', True, '公因數必須是兩個數的因數，所以不會超過較小的數。')

# ───── 公倍數與最小公倍數（6）─────
for a, b in [(4, 6), (6, 9), (8, 12)]:
    l = lcm(a, b)
    mc('公倍數', f'{a} 和 {b} 的最小公倍數是多少？', l, [a * b if a * b != l else l * 2, l // 2 if l % 2 == 0 and l // 2 != gcd(a, b) else l + a, gcd(a, b)],
       f'{a} 的倍數：{fl([a*i for i in range(1, 5)])}……；{b} 的倍數：{fl([b*i for i in range(1, 4)])}……，最小的公倍數是 {l}。')
mc('公倍數', '3 和 5 的公倍數中，100 以內最大的是多少？', 90, [95, 99, 75], '3 和 5 的最小公倍數是 15，100 以內 15 的倍數最大是 90。')
tf('公倍數', '兩個數的公倍數有無限多個。', True, '最小公倍數的每一個倍數都是公倍數，有無限多個。')
tf('公倍數', '6 和 8 的最小公倍數是 48。', False, '6 的倍數 6、12、18、24……；8 的倍數 8、16、24……，最小公倍數是 24。')

