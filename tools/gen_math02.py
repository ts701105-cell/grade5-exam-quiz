mc('應用題', '有 24 顆糖果，要平分給幾個人才能剛好分完、沒有剩下？下列哪一個人數「不行」？', 5, [3, 4, 6], '24 的因數是 1、2、3、4、6、8、12、24，5 不是 24 的因數。')
