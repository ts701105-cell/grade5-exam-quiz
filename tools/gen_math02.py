mc('應用題', '甲公車每 6 分鐘發一班，乙公車每 8 分鐘發一班。早上 7:00 同時發車，下一次同時發車是幾點幾分？', '7:24', ['7:48', '7:14', '7:12'], '6 和 8 的最小公倍數是 24，所以 24 分鐘後，也就是 7:24。')
mc('應用題', '一盒巧克力可以平分給 4 人，也可以平分給 6 人，都剛好分完。這盒巧克力最少有幾顆？', 12, [24, 10, 6], '要同時是 4 和 6 的倍數，最少是最小公倍數 12 顆。')
mc('應用題', '小華每 3 天去一次圖書館，小美每 4 天去一次。今天兩人同時去，至少再過幾天會再同時去？', 12, [7, 6, 24], '3 和 4 的最小公倍數是 12，再過 12 天。')
mc('應用題', '有 48 顆蘋果要裝袋，每袋裝的顆數相同、沒有剩下，而且每袋超過 10 顆，可以每袋裝幾顆？', 12, [10, 9, 14], '48 的因數中大於 10 的有 12、16、24、48，選項中只有 12 符合。')
