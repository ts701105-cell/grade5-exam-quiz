Q = []
def lcm(a, b): return a * b // gcd(a, b)
def factors(n): return [d for d in range(1, n + 1) if n % d == 0]
def fl(xs): return '、'.join(map(str, xs))
def fr(a, b): return f'[{a}/{b}]'

def mc(cat, q, right, wrongs, exp, **kw):
    opts = [str(right)] + [str(w) for w in wrongs]
    assert len(opts) == 4 and len(set(opts)) == 4, (q, opts)
    Q.append(dict(type='mc', cat=cat, q=q, opts=opts, ans=0, exp=exp, **kw))

def tf(cat, q, ok, exp):
    Q.append(dict(type='tf', cat=cat, q=q, opts=['○ 正確', '✕ 錯誤'], ans=0 if ok else 1, exp=exp))

