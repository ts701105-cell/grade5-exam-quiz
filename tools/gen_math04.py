# 4-1 擴分　4-2 約分　4-3 通分和異分母分數的大小比較
# 分數在題目中寫成 [分子/分母]，網站會顯示成上下排列。
import json, random
from fractions import Fraction as F
from math import gcd
random.seed(4)
Q = []

def fr(a, b): return f'[{a}/{b}]'
def lcm(a, b): return a * b // gcd(a, b)

def mc(cat, q, right, wrongs, exp):
    wrongs = [w for w in dict.fromkeys(map(str, wrongs)) if w != str(right)][:3]
    assert len(wrongs) == 3, (q, right, wrongs)
    opts = [str(right)] + wrongs
    random.shuffle(opts)
    Q.append({'type': 'mc', 'cat': cat, 'q': q, 'opts': opts, 'ans': opts.index(str(right)), 'exp': exp})

def tf(cat, q, ok, exp):
    Q.append({'type': 'tf', 'cat': cat, 'q': q, 'opts': ['○ 正確', '✕ 錯誤'], 'ans': 0 if ok else 1, 'exp': exp})

# ═══════ 4-1 擴分（13）═══════
for a, b, k in [(2, 3, 4), (3, 5, 3), (5, 7, 2)]:
    mc('擴分', f'把 {fr(a, b)} 的分子和分母同時乘以 {k}，會得到哪一個分數？', fr(a * k, b * k), [fr(a * k, b), fr(a, b * k), fr(a + k, b + k)],
       f'擴分時分子、分母要同時乘以 {k}：{fr(a, b)} = {fr(a * k, b * k)}，分數大小不變。')
for a, b, nb in [(3, 4, 20), (2, 9, 27), (5, 6, 42)]:
    na = a * nb // b
    mc('擴分', f'{fr(a, b)} = {fr("□", nb)}，□ 是多少？'.replace('[□/', '[□/'), na, [na + 1, a * (nb - b), nb - b + a],
       f'{b} × {nb // b} = {nb}，分子也要 × {nb // b}：{a} × {nb // b} = {na}。')
for a, b in [(3, 8), (4, 5)]:
    k = random.choice([2, 3, 4])
    right = fr(a * k, b * k)
    mc('擴分', f'下列哪一個分數和 {fr(a, b)} 一樣大？', right, [fr(a * k, b * k + 1), fr(a + k, b + k), fr(a * k + 1, b * k)],
       f'{fr(a, b)} 的分子和分母同乘以 {k}，得到 {right}，是等值分數。')
mc('擴分', f'{fr(1, 2)} 擴分後，分母是 10，分子是多少？', 5, [2, 9, 1], '分母 2 × 5 = 10，分子 1 × 5 = 5，得到 [5/10]。')
mc('擴分', '擴分的時候，分子和分母要怎麼做？', '同時乘以相同的數（0 除外）', ['同時加上相同的數', '只把分母乘以一個數', '同時減去相同的數'], '分子、分母同乘一個不為 0 的數，分數大小不變。')
tf('擴分', f'{fr(2, 5)} 的分子和分母同時加上 3，得到 {fr(5, 8)}，兩個分數一樣大。', False, f'擴分要「乘」不能「加」；{fr(2, 5)} = 0.4，{fr(5, 8)} = 0.625，不一樣大。')
tf('擴分', f'{fr(4, 6)}、{fr(6, 9)}、{fr(8, 12)} 都和 {fr(2, 3)} 一樣大。', True, f'它們都是 {fr(2, 3)} 擴分得到的等值分數。')
tf('擴分', '擴分以後，分數會變大。', False, '擴分只是分得更細，分數的大小不變。')

# ═══════ 4-2 約分（15）═══════
for a, b in [(12, 18), (16, 24), (15, 35), (28, 42), (36, 48)]:
    g = gcd(a, b); x = F(a, b)
    half = fr(a // 2, b // 2) if a % 2 == 0 and b % 2 == 0 and g != 2 else fr(a // g * 2, b // g * 2)
    mc('約分', f'把 {fr(a, b)} 約成最簡分數，答案是多少？', fr(x.numerator, x.denominator),
       [half, fr(x.denominator, x.numerator), fr(x.numerator + 1, x.denominator + 1)],
       f'{a} 和 {b} 的最大公因數是 {g}，分子分母同除以 {g}：{fr(a, b)} = {fr(x.numerator, x.denominator)}。')
mc('約分', f'下列哪一個是最簡分數？', fr(7, 12), [fr(6, 9), fr(10, 15), fr(8, 14)], '最簡分數的分子和分母只有公因數 1；7 和 12 的公因數只有 1。')
mc('約分', f'下列哪一個「不是」最簡分數？', fr(9, 15), [fr(4, 9), fr(5, 8), fr(11, 13)], '9 和 15 有公因數 3，還可以約成 [3/5]。')
mc('約分', f'{fr(24, 36)} 要一次約到最簡，分子和分母要同時除以多少？', 12, [6, 4, 24], '24 和 36 的最大公因數是 12，同除以 12 得 [2/3]。')
for a, b, nb in [(15, 25, 5), (18, 27, 3), (20, 32, 8)]:
    na = a * nb // b
    mc('約分', f'{fr(a, b)} = {fr("□", nb)}，□ 是多少？', na, [na + 1, a - nb, na * 2],
       f'{b} ÷ {b // nb} = {nb}，分子也要 ÷ {b // nb}：{a} ÷ {b // nb} = {na}。')
mc('約分', '什麼是「最簡分數」？', '分子和分母的公因數只有 1 的分數', ['分子是 1 的分數', '分母最小的分數', '分子比分母小的分數'], '分子、分母沒有 1 以外的公因數，就不能再約分了。')
tf('約分', '約分時，分子和分母要同時除以它們的公因數，分數大小不變。', True, '同除以相同的數（0 除外），大小不變。')
tf('約分', f'{fr(10, 16)} 約成最簡分數是 {fr(5, 8)}。', True, '10 和 16 的最大公因數是 2，同除以 2 得 [5/8]。')
tf('約分', f'{fr(6, 8)} 約分後是 {fr(3, 8)}。', False, '分子分母要「同時」除以 2：[6/8] = [3/4]，不能只除分子。')

# ═══════ 4-3 通分與比較（17）═══════
for (a, b), (c, d) in [((2, 3), (3, 4)), ((1, 6), (3, 8)), ((3, 5), (1, 2)), ((5, 6), (4, 9))]:
    L = lcm(b, d)
    r = f'{fr(a * L // b, L)} 和 {fr(c * L // d, L)}'
    w1 = f'{fr(a * b * d // b, b * d)} 和 {fr(c * b * d // d + 1, b * d)}'
    w2 = f'{fr(a, L)} 和 {fr(c, L)}'
    w3 = f'{fr(a + c, L)} 和 {fr(c, L)}'
    mc('通分', f'把 {fr(a, b)} 和 {fr(c, d)} 用最小公分母通分，結果是哪一個？', r, [w1, w2, w3],
       f'{b} 和 {d} 的最小公倍數是 {L}；{fr(a, b)} = {fr(a * L // b, L)}，{fr(c, d)} = {fr(c * L // d, L)}。')
for b, d in [(4, 6), (8, 12), (9, 6)]:
    L = lcm(b, d)
    mc('通分', f'分母 {b} 和 {d} 通分時，最小的公分母是多少？', L, [b * d if b * d != L else L * 2, gcd(b, d), L + b],
       f'公分母要是 {b} 和 {d} 的公倍數，最小公倍數是 {L}。')
for (a, b), (c, d) in [((3, 5), (4, 7)), ((5, 8), (2, 3)), ((7, 10), (3, 4))]:
    x, y = F(a, b), F(c, d)
    L = lcm(b, d)
    big = fr(a, b) if x > y else fr(c, d)
    mc('分數比大小', f'{fr(a, b)} 和 {fr(c, d)}，哪一個比較大？', big, [fr(c, d) if x > y else fr(a, b), '一樣大', '無法比較'],
       f'通分成分母 {L}：{fr(a * L // b, L)} 和 {fr(c * L // d, L)}，分子大的比較大，所以 {big} 比較大。')
fs = [(2, 3), (3, 4), (5, 8)]
order = sorted(fs, key=lambda t: F(*t))
mc('分數比大小', f'把 {fr(2, 3)}、{fr(3, 4)}、{fr(5, 8)} 由小到大排列，正確的是？', '<'.join(fr(*t) for t in order),
   ['<'.join(fr(*t) for t in fs), '<'.join(fr(*t) for t in reversed(order)), '<'.join(fr(*t) for t in [order[1], order[0], order[2]])],
   '通分成分母 24：[16/24]、[18/24]、[15/24]，所以 [5/8] < [2/3] < [3/4]。')
mc('分數比大小', f'下列哪一個分數比 {fr(1, 2)} 大？', fr(5, 9), [fr(3, 7), fr(4, 9), fr(2, 5)], '和 [1/2] 比：分子的 2 倍比分母大，分數就大於 [1/2]；5 × 2 = 10 > 9。')
mc('分數比大小', f'分子相同時，{fr(3, 7)} 和 {fr(3, 10)} 哪一個比較大？', fr(3, 7), [fr(3, 10), '一樣大', '無法比較'], '分子相同，分母越小（分的份數越少），每份越大，所以 [3/7] 較大。')
tf('分數比大小', '異分母分數比大小，可以先通分成同分母，再比較分子。', True, '同分母時，分子大的分數比較大。')
tf('分數比大小', f'{fr(4, 5)} 比 {fr(5, 6)} 大。', False, '通分成分母 30：[24/30] < [25/30]，所以 [4/5] 比 [5/6] 小。')
tf('通分', '通分時，公分母只能用兩個分母相乘的積。', False, '公分母可以用任何公倍數，通常用最小公倍數比較好算。')

