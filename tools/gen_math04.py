mc('應用題', f'哥哥吃了一個披薩的 {fr(3, 8)}，弟弟吃了同樣大小披薩的 {fr(1, 3)}，誰吃得比較多？', '哥哥', ['弟弟', '一樣多', '無法比較'], '通分成分母 24：哥哥 [9/24]，弟弟 [8/24]，哥哥吃得比較多。')
mc('應用題', f'小明 {fr(3, 4)} 小時寫完作業，小華 {fr(5, 6)} 小時寫完，誰寫得比較快？', '小明', ['小華', '一樣快', '無法比較'], '通分成分母 12：小明 [9/12]，小華 [10/12]，小明用的時間比較少，所以比較快。')
mc('應用題', f'一條緞帶長 1 公尺，用掉 {fr(12, 20)} 公尺，用掉的長度約成最簡分數是多少公尺？', fr(3, 5), [fr(6, 10), fr(2, 5), fr(12, 20)], '12 和 20 的最大公因數是 4，[12/20] = [3/5]。')
mc('應用題', f'甲杯有 {fr(2, 5)} 公升果汁，乙杯有 {fr(3, 7)} 公升果汁，哪一杯比較多？', '乙杯', ['甲杯', '一樣多', '無法比較'], '通分成分母 35：甲 [14/35]，乙 [15/35]，乙杯比較多。')
